CREATE TABLE preparation_tasks (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    encounter_id INTEGER NOT NULL REFERENCES encounters(id), bed_id INTEGER REFERENCES bed_registry(id),
    title VARCHAR(200) NOT NULL CHECK(btrim(title)<>''), description TEXT,
    task_type VARCHAR(30) NOT NULL CHECK(task_type IN ('EQUIPMENT','ROOM','RESOURCE','OTHER')),
    status VARCHAR(20) NOT NULL DEFAULT 'OPEN' CHECK(status IN ('OPEN','IN_PROGRESS','BLOCKED','COMPLETED','CANCELLED')),
    is_required BOOLEAN NOT NULL DEFAULT true, assigned_to INTEGER REFERENCES users(id),
    assigned_department_id INTEGER REFERENCES departments(id), created_by INTEGER NOT NULL REFERENCES users(id),
    due_at TIMESTAMPTZ, started_at TIMESTAMPTZ, completed_at TIMESTAMPTZ,
    completed_by INTEGER REFERENCES users(id), blocked_reason TEXT, cancelled_reason TEXT,
    version INTEGER NOT NULL DEFAULT 1 CHECK(version>0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(encounter_id,id),
    CHECK(status<>'BLOCKED' OR nullif(btrim(blocked_reason),'') IS NOT NULL),
    CHECK(status<>'CANCELLED' OR nullif(btrim(cancelled_reason),'') IS NOT NULL),
    CHECK((status='COMPLETED')=(completed_at IS NOT NULL)),
    CHECK((completed_at IS NULL)=(completed_by IS NULL))
);
CREATE TABLE activity_events (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    encounter_id INTEGER NOT NULL REFERENCES encounters(id), actor_id INTEGER REFERENCES users(id),
    event_type VARCHAR(50) NOT NULL, message TEXT NOT NULL, reason TEXT,
    occurred_at TIMESTAMPTZ NOT NULL, recorded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    is_manual_entry BOOLEAN NOT NULL DEFAULT false, changes JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK(event_type<>'DOCTOR_OVERRIDE' OR (actor_id IS NOT NULL AND nullif(btrim(reason),'') IS NOT NULL))
);
CREATE TABLE alerts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    encounter_id INTEGER NOT NULL REFERENCES encounters(id), task_id INTEGER,
    alert_type VARCHAR(50) NOT NULL, severity VARCHAR(20) NOT NULL CHECK(severity IN ('INFO','ACTION','URGENT')),
    message TEXT NOT NULL, deduplication_key VARCHAR(150) NOT NULL,
    resolved_at TIMESTAMPTZ, resolved_by INTEGER REFERENCES users(id), resolution_reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY(encounter_id,task_id) REFERENCES preparation_tasks(encounter_id,id)
);
CREATE UNIQUE INDEX alerts_unresolved_key_uq ON alerts(deduplication_key) WHERE resolved_at IS NULL;
CREATE TABLE alert_recipients (
    alert_id INTEGER NOT NULL REFERENCES alerts(id), user_id INTEGER NOT NULL REFERENCES users(id),
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT now(), seen_at TIMESTAMPTZ,
    acknowledged_at TIMESTAMPTZ, escalation_due_at TIMESTAMPTZ, escalated_at TIMESTAMPTZ,
    PRIMARY KEY(alert_id,user_id)
);
CREATE TABLE request_idempotency (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(), user_id INTEGER NOT NULL REFERENCES users(id),
    request_key VARCHAR(100) NOT NULL, operation VARCHAR(100) NOT NULL, request_hash TEXT NOT NULL,
    response_status SMALLINT CHECK(response_status BETWEEN 100 AND 599), response_body JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(), expires_at TIMESTAMPTZ NOT NULL,
    UNIQUE(user_id,operation,request_key), CHECK(expires_at>created_at)
);
CREATE TABLE outbox_events (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(), event_type VARCHAR(50) NOT NULL,
    entity_type VARCHAR(50) NOT NULL, entity_id INTEGER NOT NULL, entity_version INTEGER NOT NULL CHECK(entity_version>0),
    payload JSONB NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now(), published_at TIMESTAMPTZ,
    attempt_count INTEGER NOT NULL DEFAULT 0 CHECK(attempt_count>=0), next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

