CREATE TABLE encounters (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    encounter_code VARCHAR(50) NOT NULL UNIQUE,
    patient_record_id INTEGER NOT NULL REFERENCES patient_records(id),
    department_id INTEGER NOT NULL REFERENCES departments(id),
    chief_complaint TEXT NOT NULL, diagnosis TEXT,
    reported_age_years SMALLINT CHECK(reported_age_years BETWEEN 0 AND 130),
    reported_acuity VARCHAR(20) NOT NULL DEFAULT 'UNKNOWN'
        CHECK(reported_acuity IN ('UNKNOWN','ROUTINE','URGENT','CRITICAL')),
    status VARCHAR(20) NOT NULL CHECK(status IN ('EN_ROUTE','ARRIVED','IN_CARE','DISCHARGED','TRANSFERRED','CANCELLED')),
    interim_location VARCHAR(100), created_by INTEGER NOT NULL REFERENCES users(id),
    arrived_at TIMESTAMPTZ, arrival_confirmed_by INTEGER REFERENCES users(id),
    handoff_accepted_at TIMESTAMPTZ, handoff_accepted_by INTEGER REFERENCES users(id),
    care_started_at TIMESTAMPTZ, closed_at TIMESTAMPTZ, closed_by INTEGER REFERENCES users(id),
    closure_reason TEXT, transfer_destination VARCHAR(150), purge_after TIMESTAMPTZ,
    version INTEGER NOT NULL DEFAULT 1 CHECK(version>0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK((arrived_at IS NULL) = (arrival_confirmed_by IS NULL)),
    CHECK((handoff_accepted_at IS NULL) = (handoff_accepted_by IS NULL)),
    CHECK((status IN ('DISCHARGED','TRANSFERRED','CANCELLED')) = (closed_at IS NOT NULL)),
    CHECK((closed_at IS NULL) = (closed_by IS NULL)),
    CHECK((closed_at IS NULL) = (purge_after IS NULL)),
    CHECK(purge_after IS NULL OR purge_after >= closed_at),
    CHECK(status <> 'CANCELLED' OR nullif(btrim(closure_reason),'') IS NOT NULL),
    CHECK(status <> 'TRANSFERRED' OR nullif(btrim(transfer_destination),'') IS NOT NULL)
);
CREATE TABLE ems_transports (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    encounter_id INTEGER NOT NULL UNIQUE REFERENCES encounters(id),
    agency_id INTEGER NOT NULL REFERENCES agencies(id), submitted_by INTEGER NOT NULL REFERENCES users(id),
    transport_reference VARCHAR(80) NOT NULL, unit_identifier VARCHAR(40),
    expected_arrival_at TIMESTAMPTZ NOT NULL, eta_updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    treatments_administered TEXT, notes TEXT, acknowledged_at TIMESTAMPTZ,
    acknowledged_by INTEGER REFERENCES users(id), version INTEGER NOT NULL DEFAULT 1 CHECK(version>0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(agency_id,transport_reference),
    CHECK((acknowledged_at IS NULL) = (acknowledged_by IS NULL))
);
CREATE TABLE patient_observations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    encounter_id INTEGER NOT NULL REFERENCES encounters(id), recorded_by INTEGER NOT NULL REFERENCES users(id),
    observed_at TIMESTAMPTZ NOT NULL, source VARCHAR(20) NOT NULL CHECK(source IN ('EMS','HOSPITAL')),
    heart_rate_bpm SMALLINT CHECK(heart_rate_bpm>=0),
    systolic_bp_mmhg SMALLINT CHECK(systolic_bp_mmhg>=0),
    diastolic_bp_mmhg SMALLINT CHECK(diastolic_bp_mmhg>=0),
    respiratory_rate_per_min SMALLINT CHECK(respiratory_rate_per_min>=0),
    oxygen_saturation_pct NUMERIC(5,2) CHECK(oxygen_saturation_pct BETWEEN 0 AND 100),
    temperature_c NUMERIC(4,1), notes TEXT, corrects_observation_id INTEGER,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(), UNIQUE(encounter_id,id),
    FOREIGN KEY(encounter_id,corrects_observation_id) REFERENCES patient_observations(encounter_id,id),
    CHECK(corrects_observation_id IS NULL OR corrects_observation_id<>id),
    CHECK(num_nonnulls(heart_rate_bpm,systolic_bp_mmhg,diastolic_bp_mmhg,
        respiratory_rate_per_min,oxygen_saturation_pct,temperature_c)>0 OR nullif(btrim(notes),'') IS NOT NULL)
);
CREATE TABLE bed_assignments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    encounter_id INTEGER NOT NULL REFERENCES encounters(id), bed_id INTEGER NOT NULL REFERENCES bed_registry(id),
    assigned_by INTEGER NOT NULL REFERENCES users(id), assigned_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    ended_at TIMESTAMPTZ, ended_by INTEGER REFERENCES users(id), end_reason VARCHAR(100),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK(ended_at IS NULL OR ended_at>=assigned_at),
    CHECK((ended_at IS NULL)=(ended_by IS NULL))
);
CREATE UNIQUE INDEX bed_assignments_active_bed_uq ON bed_assignments(bed_id) WHERE ended_at IS NULL;
CREATE UNIQUE INDEX bed_assignments_active_encounter_uq ON bed_assignments(encounter_id) WHERE ended_at IS NULL;
