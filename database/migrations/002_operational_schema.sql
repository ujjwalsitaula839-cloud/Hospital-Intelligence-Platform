-- Index all remaining referencing key prefixes for efficient FK checks/deletion.
DO $$ DECLARE r record; BEGIN
    FOR r IN SELECT c.conrelid::regclass AS tbl, c.conname,
        string_agg(quote_ident(a.attname), ',' ORDER BY u.ordinality) AS cols
        FROM pg_constraint c CROSS JOIN LATERAL unnest(c.conkey) WITH ORDINALITY AS u(attnum,ordinality)
        JOIN pg_attribute a ON a.attrelid=c.conrelid AND a.attnum=u.attnum
        WHERE c.contype='f' AND c.connamespace='public'::regnamespace
        AND c.conrelid IN ('users'::regclass,'user_roles'::regclass,'bed_registry'::regclass,
          'encounters'::regclass,'ems_transports'::regclass,'patient_observations'::regclass,
          'bed_assignments'::regclass,'nurse_assignments'::regclass,'preparation_tasks'::regclass,
          'activity_events'::regclass,'alerts'::regclass,'alert_recipients'::regclass,'request_idempotency'::regclass)
        GROUP BY c.oid,c.conrelid,c.conname
    LOOP EXECUTE format('CREATE INDEX %I ON %s (%s)', 'fk_'||left(r.conname,45)||'_'||left(md5(r.conname),10), r.tbl, r.cols); END LOOP;
END $$;

CREATE FUNCTION hip_touch_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN NEW.updated_at=now(); RETURN NEW; END $$;
DO $$ DECLARE t text; BEGIN
    FOREACH t IN ARRAY ARRAY['departments','agencies','users','patient_records','bed_registry',
        'encounters','ems_transports','preparation_tasks','alerts']
    LOOP EXECUTE format('CREATE TRIGGER hip_updated_at BEFORE UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION hip_touch_updated_at()',t); END LOOP;
END $$;

-- Legacy registration still supplies username, but not full_name.
CREATE FUNCTION hip_default_full_name() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN IF NEW.full_name IS NULL THEN NEW.full_name=NEW.username; END IF; RETURN NEW; END $$;
CREATE TRIGGER hip_user_full_name BEFORE INSERT ON users FOR EACH ROW EXECUTE FUNCTION hip_default_full_name();
